-- Run manually after the existing schema. Repeatable; no training data changes.
CREATE TABLE IF NOT EXISTS challenge_weekly (
 user_id INT UNSIGNED NOT NULL, iso_year SMALLINT UNSIGNED NOT NULL, iso_week TINYINT UNSIGNED NOT NULL,
 completed_loops INT UNSIGNED NOT NULL DEFAULT 0, run_count INT UNSIGNED NOT NULL DEFAULT 0,
 finalized TINYINT NOT NULL DEFAULT 0, updated_at DATETIME NOT NULL,
 PRIMARY KEY(user_id,iso_year,iso_week), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS supporters (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(40) COLLATE utf8mb4_unicode_ci NOT NULL UNIQUE,
 display_name VARCHAR(80) NOT NULL, password_hash VARCHAR(255) NOT NULL,
 session_version INT UNSIGNED NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS supporter_tokens (
 selector CHAR(24) PRIMARY KEY, supporter_id INT UNSIGNED NOT NULL, token_hash CHAR(64) NOT NULL,
 expires_at DATETIME NOT NULL, INDEX(expires_at), FOREIGN KEY(supporter_id) REFERENCES supporters(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS supporter_limits (
 bucket CHAR(64) PRIMARY KEY, hits INT UNSIGNED NOT NULL DEFAULT 1, expires_at DATETIME NOT NULL, INDEX(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS supporter_cheers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, supporter_id INT UNSIGNED NULL, runner_id INT UNSIGNED NOT NULL,
 message VARCHAR(240) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(runner_id,created_at), INDEX(supporter_id,created_at),
 FOREIGN KEY(supporter_id) REFERENCES supporters(id) ON DELETE SET NULL,
 FOREIGN KEY(runner_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS supporter_tips (
 supporter_id INT UNSIGNED NOT NULL, iso_year SMALLINT UNSIGNED NOT NULL, iso_week TINYINT UNSIGNED NOT NULL,
 runner_id INT UNSIGNED NOT NULL, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(supporter_id,iso_year,iso_week), INDEX(iso_year,iso_week),
 FOREIGN KEY(supporter_id) REFERENCES supporters(id) ON DELETE CASCADE,
 FOREIGN KEY(runner_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS supporter_sharing (
 runner_id INT UNSIGNED PRIMARY KEY, approved_at DATETIME NOT NULL,
 FOREIGN KEY(runner_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS push_subscriptions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, runner_id INT UNSIGNED NULL, supporter_id INT UNSIGNED NULL,
 endpoint_hash CHAR(64) NOT NULL UNIQUE, subscription TEXT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(runner_id), INDEX(supporter_id),
 FOREIGN KEY(runner_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(supporter_id) REFERENCES supporters(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS supporter_push_jobs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, cheer_id BIGINT UNSIGNED NOT NULL,
 attempts TINYINT UNSIGNED NOT NULL DEFAULT 0, available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(available_at), FOREIGN KEY(cheer_id) REFERENCES supporter_cheers(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS supporter_push_deliveries (
 job_id BIGINT UNSIGNED NOT NULL, subscription_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(job_id,subscription_id),
 FOREIGN KEY(job_id) REFERENCES supporter_push_jobs(id) ON DELETE CASCADE,
 FOREIGN KEY(subscription_id) REFERENCES push_subscriptions(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
